import fs from "node:fs";
import { parse } from "yaml";
import {
  currentSourceInspection,
  sourceFingerprint,
} from "./review-evidence.mjs";
const inspections = JSON.parse(
  fs.readFileSync("content/review/source-inspections.json", "utf8"),
);
const approvals = JSON.parse(
  fs.readFileSync("content/review/evidence.json", "utf8"),
);
const revision = JSON.parse(
  fs.readFileSync("content/revision/foundation.json", "utf8"),
);
const lessons = fs
  .readdirSync("content/lessons")
  .filter((f) => f.endsWith(".mdx"))
  .sort()
  .map((file) => {
    const source = fs.readFileSync("content/lessons/" + file, "utf8"),
      data = parse(/^---\n([\s\S]*?)\n---/.exec(source)[1]);
    const sources = currentSourceInspection(data.id, source, inspections);
    return {
      lessonId: data.id,
      title: data.title,
      sha256: sourceFingerprint(source),
      status: data.status,
      sections: [...source.matchAll(/<LessonSection id="([^"]+)"/g)].map(
        (m) => m[1],
      ),
      questions: data.questions.length,
      duplicatePromptIds: data.questions
        .filter(
          (q, i, a) =>
            a.findIndex(
              (p) =>
                p.prompt.trim().toLowerCase() === q.prompt.trim().toLowerCase(),
            ) !== i,
        )
        .map((q) => q.id),
      missingHints: data.questions.filter((q) => !q.hint).map((q) => q.id),
      shortExplanations: data.questions
        .filter((q) => q.explanation.trim().length < 90)
        .map((q) => q.id),
      unspecifiedNumericUnits: data.questions
        .filter(
          (q) =>
            q.type === "numeric" && (!q.unit || /as specified/i.test(q.unit)),
        )
        .map((q) => q.id),
      sourceScope: sources.length
        ? "partial AI-assisted source inspection"
        : "no current source mapping",
      inspectedSourceCount: sources.reduce((n, s) => n + s.sources.length, 0),
      independentApproval: (approvals.reviews || []).some(
        (a) =>
          a.lessonId === data.id &&
          a.independent === true &&
          a.decision === "approved" &&
          a.sha256 === sourceFingerprint(source),
      ),
      newWorkedInference: source.includes("### Worked inference:"),
      revisionEnriched: revision.modules.some(
        (m) =>
          m.id === data.id &&
          m.examples.length >= 3 &&
          m.checks.some((q) => q.optional),
      ),
      nextReview:
        "A qualified reviewer must check all derivations, question answers, source scopes and actual model code; editorial flags alone neither prove nor disprove correctness.",
    };
  });
const summary = {
  lessons: lessons.length,
  questions: lessons.reduce((n, l) => n + l.questions, 0),
  currentPartialSourceMappings: lessons.filter((l) => l.inspectedSourceCount)
    .length,
  withoutCurrentSourceMapping: lessons.filter((l) => !l.inspectedSourceCount)
    .length,
  independentApprovals: lessons.filter((l) => l.independentApproval).length,
  enrichedRevisionChapters: revision.modules.filter(
    (m) => m.examples.length >= 3,
  ).length,
  workedRevisionExamples: revision.modules.reduce(
    (n, m) => n + m.examples.length,
    0,
  ),
  revisionPracticeQuestions: revision.modules.reduce(
    (n, m) => n + m.checks.length,
    0,
  ),
  newAstronomyWorkedCases: lessons.filter((l) => l.newWorkedInference).length,
};
const report = {
  scope:
    "Course-wide editorial and evidence audit, not a completed scientific review. Source mappings remain scoped and AI-assisted; numerical tests establish selected calculations only. No human identity, qualification, approval or learner score is manufactured.",
  summary,
  lessons,
};
fs.writeFileSync(
  "content/review/scientific-audit.json",
  JSON.stringify(report, null, 2) + "\n",
);
fs.writeFileSync(
  "docs/CURRENT-REVIEW-STATUS.md",
  `# Current review and enrichment status\n\nGenerated by \`node scripts/scientific-audit.mjs\`. This audit covers all ${summary.lessons} authored lessons and ${summary.questions} bank questions. It is not full scientific certification.\n\n- ${summary.currentPartialSourceMappings} lessons have current, scoped AI-assisted source inspections; ${summary.withoutCurrentSourceMapping} have no current mapping.\n- ${summary.independentApprovals} current independent approvals. All lessons remain drafts.\n- All ${summary.enrichedRevisionChapters} foundation revision chapters now have three worked examples and an optional transfer problem: ${summary.workedRevisionExamples} examples and ${summary.revisionPracticeQuestions} questions. The existing three-check completion rule is retained.\n- ${summary.newAstronomyWorkedCases} astronomy lessons add a worked inference and a separate numerical transfer: celestial geometry, seasons, orbital periods, luminosity inference, blackbody peaks, Doppler estimates, exoplanet transits and local Hubble distances. These explicitly distinguish assumptions from observational conclusions.\n\nThe JSON audit records each lesson's source fingerprint, question count, missing hints, short explanations, unspecified numeric units and source/approval state. Those editorial flags identify work for a reviewer; they are not automatic scientific errors and have not been hidden by template filler.\n\n## What remains external\n\nA qualified independent reviewer must inspect the current text, every worked answer and actual simulation implementation, record exact sources and return genuine decisions. An authoring agent cannot independently approve its own work. Remaining source scopes and advanced-course depth are still open; this release does not claim equal richness or a new bespoke simulation for every one of the 354 lessons.\n\nUse \`npm run review:handoff -- NEW_DIRECTORY\` for a fresh artifact-bound handoff, and the existing evidence gate before changing any lesson to verified/published. Revision guides are separately unapproved and included in review packets. Positive learner feedback and reported working sync/reminders do not substitute for scientific approval or scored learning evidence.\n`,
);
